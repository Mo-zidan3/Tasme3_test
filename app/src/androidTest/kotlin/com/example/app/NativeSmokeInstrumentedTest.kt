/**
 * CI emulator job (API 27 + modern API) — closes S2, Q8-on-device, and the minSdk question
 * (V-016) in one run:
 *  1. System.loadLibrary smoke for both prebuilt .so (the definitive native-floor answer);
 *  2. TIMING decode on a DETERMINISTIC generated fixture (scripts/make_timing_fixture.py —
 *     code, not a binary; no third-party/gated audio): asserts tokens are produced, timestamps
 *     are SECONDS-scale, and consecutive deltas are multiples of the 40 ms frame shift
 *     (V-015 must reproduce ON DEVICE);
 *  3. ACCURACY decode on Mo's own clip — loud-skip while absent (fixture policy);
 *  4. AmiriQuran.ttf shaping smoke (codepoints render non-empty).
