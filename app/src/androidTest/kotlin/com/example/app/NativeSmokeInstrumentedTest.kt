    /** 16 kHz mono 16-bit PCM → float [-1,1]; returns (samples, durationMs). */
    private fun readMono16kPcm(wav: File): Pair<FloatArray, Long> {
        val header = wav.inputStream().use { it.readBytes() }
        // naive WAV parse: find "data" chunk
        var idx = 12
        var dataOff = -1
        var dataLen = 0
        while (idx + 8 <= header.size) {
            val id = String(header, idx, 4, Charsets.US_ASCII)
            val size = leInt(header, idx + 4)
            if (id == "data") {
                dataOff = idx + 8
                dataLen = size
                break
            }
            idx += 8 + size + (size and 1)
        }
        assertTrue("no data chunk in ${wav.name}", dataOff > 0)
        val samples = ByteArray(dataLen)
        System.arraycopy(header, dataOff, samples, 0, dataLen)
        val pcm = FloatArray(dataLen / 2) { i ->
            val s = ((samples[2 * i].toInt() and 0xFF) or ((samples[2 * i + 1].toByte().toInt() shl 8)))
            s / 32768f
        }
        return pcm to (pcm.size * 1000L / 16000)
    }

    private fun leInt(b: ByteArray, off: Int): Int =
        (b[off].toInt() and 0xFF) or ((b[off + 1].toInt() and 0xFF) shl 8) or
            ((b[off + 2].toInt() and 0xFF) shl 16) or ((b[off + 3].toInt() and 0xFF) shl 24)

    /** timestamps from the recognizer's result — via the vendored API result object. */
    private fun wordsTimestampsMs(
        recognizer: com.example.core.asr.SherpaOnnxRecognizer,
        result: com.example.core.asr.AsrResult,
    ): List<Long> {
        val words = result.words
        if (words.isEmpty()) return emptyList()
        if (words[0].startMs == null) return emptyList() // explicit null-timing fallback
        assertNotNull(recognizer)
        return words.mapNotNull { it.startMs }
    }
