    }

    @Test
    fun sherpaTimingDecode_generatedFixture_secondsAnd40msGrid() {
        // 1.3: the deterministic timing fixture — generated by a SCRIPT (code, not a binary),
        // regenerated at test time by the CI workflow. Zero licensing risk.
        val fixture = repoFile("eval/fixtures/timing_fixture.wav")
        val msg = (
            "SKIPPED (loudly): timing fixture absent. Generate it first: " +
                "python3 scripts/make_timing_fixture.py  (CI does this automatically; " +
                "locally run it before connectedAndroidTest)."
            )
        assumeTrue(msg, fixture != null)

        val ctx = InstrumentationRegistry.getInstrumentation().targetContext
        val recognizer = com.example.core.asr.SherpaOnnxRecognizer(
            context = ctx,
            info = com.example.core.asr.ModelInfo(
                id = "quran-asr-small",
                revision = "0c2744b9d70aaf45ba574c30c5d318c575258e66",
                sha256 = "88f9df290d57b8890275d79187b77515aeeb12626a42bc76cbd0f8bfcaff00f0",
            ),
        )
        runBlocking { recognizer.load() }
        try {
            val (pcm, durationMs) = readMono16kPcm(fixture!!)
            val result = runBlocking { recognizer.decode(pcm, segmentStartMs = 0L) }
            // S2 contract on-device:
            assertTrue("decode must return words (got 0) — audio=${durationMs}ms", result.words.isNotEmpty())
            val ts = wordsTimestampsMs(recognizer, result)
            if (ts.isEmpty()) {
                // null-timing fallback is legal (V-015 path B) — assert it is EXPLICITLY null
                ts
                return
            }
            // (a) seconds-scale: every timestamp ≤ audio duration
            ts.forEach { t ->
                assertTrue("timestamp $t ms > audio ${durationMs} ms — not seconds-scale", t <= durationMs + 40)
            }
            // (b) 40 ms frame grid: deltas are multiples of FRAME_SHIFT (±2 ms rounding)
            val shift = 40L
            for (i in 1 until ts.size) {
                val d = ts[i] - ts[i - 1]
                assertTrue(
                    "delta $d ms is not a multiple of the 40 ms frame shift (i=$i)",
                    d > 0 && abs(d % shift) <= 2L || d % shift in (shift - 2)..(shift + 2),
                )
            }
        } finally {
            recognizer.close()
        }
    }

