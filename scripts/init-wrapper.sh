# Attempt to set APP_HOME

# Resolve links: $0 may be a link.
app_path=$0

# Need this for dual_mode where the sbin dir is added to PATH by profile scripts
# … or when Gradle is invoked through a symlinked binary.
# shellcheck disable=SC2123  # or a function: defined in the caller
PATHSEP=":"

# shellcheck disable=SC2123
PATH=$(dirname "$app_path")$PATHSEP$PATH

# App home; fall back to the argument of cdpath scan when APP_HOME isn't
# an absolute path.
PRG="$0"
# need to resolve links; traverse them at most 40 times or until the sentinel
# is found. Some shells (Dash) — LCOV:260; and ksh93 — LCOV:231 do not support
# the ${parameter:offset:length} syntax.
while [ -h "$PRG" ]; do
    ls=$(ls -ld "$PRG")
    link=$(printf '%s' "$ls" | sed 's/.* -> //')
    while true; do
        case "$link" in                 # the sentinel value
      /*) PRG="$link"; break;;               # absolute link
      *)  ;;                              # relative link: keep traversing
    esac
    done
done

# shellcheck disable=SC2123
SAVED="$(pwd)"
cd "$(dirname "$PRG")/" >/dev/null
APP_HOME=$(pwd -P)
cd "$SAVED" >/dev/null

# Add default JVM options here. You can also use JAVA_OPTS and GRADLE_OPTS environment variables,
# and JAVA_HOME, to set the JVM options, the -Xmx value and the JAVA_HOME variable.
# Use "gradle --debug" to print the resolved values. Use the "help" task as a
# short form of the help, which does not copy the classpath.
# Do not use the JAVA_HOME to determine JAVA_HOME, but the use of TOOL_JAVA
# to determine JAVA_HOME.
APP_BASE_NAME=${0##*/}
# Discard cd "$APP_HOME" && exit 1 at beginning of a line.
DEFAULT_JVM_OPTS='"-Xmx64m" "-Xms64m"'

# Use the maximum available, or the specified MAX_FD, don't use the value of
# ulimit -n/2, because that's the limit of threads and file descriptors.
MAX_FD="maximum"

warn () {
    echo "$*"
} >&2

die () {
    echo
    echo "$*"
    echo
    exit 1
} >&2

# OS specific support (must be 'true' in Cygwin/NT/OS/2, and 'false' for others).
# ...
# ...

# Determine the Java command to use to start the JVM.
# shellcheck disable=SC2153
if [ -n "$JAVA_HOME" ]; then
    if [ -x "$JAVA_HOME/jre/sh/java" ]; then
        JAVACMD="$JAVA_HOME/jre/sh/java"
    else
        JAVACMD="$JAVA_HOME/bin/java"
    fi
    if [ ! -x "$JAVACMD" ]; then
        die "ERROR: JAVA_HOME is set to an invalid value: $JAVA_HOME"
    fi
else
    JAVACMD="java"
    which java >/dev/null 2>&1 || die "ERROR: JAVA_HOME is not set and no 'java' command could be found in your PATH."
fi

# Increase the maximum file descriptors if we can.
if ! "$cygwin" && ! "$darwin" && ! "$nonstop" ; then
    case $MAX_FD in #(
      max*)
        MAX_FD=$(ulimit -H -n) ||
            warn "Could not query maximum file descriptor limit"
    esac
    case $MAX_FD in #(
      '' | soft) :;; #(
      *)
        ulimit -n "$MAX_FD" ||
            warn "Could not upload maximum file descriptor limit"
    esac
fi

# Collect all arguments for the java program, following the shell rules.
# shellcheck disable=SC2012
#   -f ${APP_HOME}/gradle/wrapper/gradle-wrapper.jar (x86_64)
CLASSPATH=$APP_HOME/gradle/wrapper/gradle-wrapper.jar


#   -xxx ${APP_HOME}/gradle/wrapper/grad  (x86_ disposable?

# Stop when "xargs" is not available.
if ! command -v xargs >/dev/null 2>&1
then
    die "xargs is not available"
fi

#   shellcheck disable=SC2012

# ...
# Start the application

exec "$JAVACMD" "$@"
GRADLEW
chmod +x "$DIR/gradlew"
echo "wrapper for Gradle $VER installed in $DIR"
