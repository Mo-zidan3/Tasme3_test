#!/usr/bin/env bash
# Install gradle wrapper files for a pinned Gradle version without a local Gradle install.
# Usage: bash scripts/init-wrapper.sh <gradle-version> <target-dir>
set -euo pipefail
VER="$1"; DIR="$2"
mkdir -p "$DIR/gradle/wrapper"
curl -fSL --retry 3 -o "$DIR/gradle/wrapper/gradle-wrapper.jar" \
  "https://raw.githubusercontent.com/gradle/gradle/v${VER}/gradle/wrapper/gradle-wrapper.jar"
cat > "$DIR/gradle/wrapper/gradle-wrapper.properties" <<PROPS
distributionBase=GRADLE_USER_HOME
distributionPath=wrapper/dists
distributionUrl=https\://services.gradle.org/distributions/gradle-${VER}-bin.zip
networkTimeout=10000
validateDistributionUrl=true
zipStoreBase=GRADLE_USER_HOME
zipStorePath=wrapper/dists
PROPS
# gradlew entry script from gradle v${VER} (content identical across recent versions)
cat > "$DIR/gradlew" <<'GRADLEW'
#!/bin/sh

